func TestRealImportsCachePermissionAndScopedLoading(t *testing.T) {
	report, root := fixture(t)
	sourceFile(t, root, "support/support.go", `package support
type Thing struct { Value int }
`)
	sourceFile(t, root, "dep/dep.go", `package dep
import "example.org/repo/support"
func New() support.Thing { return support.Thing{Value:7} }
`)
	sourceFile(t, root, "consumer/consumer.go", `package consumer
import "example.org/repo/dep"
var Value = dep.New().Value
`)
	sourceFile(t, root, "broken/broken.go", "package broken\nvar _ = UndefinedSymbol\n")
	cache := t.TempDir()
	t.Setenv("GOCACHE", cache)
	data, err := Read(saveFixture(t, report, false))
	if err != nil {
		t.Fatal(err)
	}
	inspect := func(allow bool) *Inspection {
		t.Helper()
		result, err := InspectRelationship(context.Background(), data, depName, "consumer", root, 10, TypeOptions{AllowExportBuilds: allow})
		if err != nil {
			t.Fatal(err)
		}
		return result
	}
	result := inspect(false)
	if !result.Complete {
		t.Fatal("real source fallback for uncached imported types failed", result.Diagnostics)
	}
	if err := filepath.WalkDir(cache, func(path string, entry os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if !entry.IsDir() && strings.HasSuffix(path, "-d") {
			// Go list may cache module indexes even in dry-run mode; these are
			// not compiler archives or evidence of a build.
			data, err := os.ReadFile(path)
			if err != nil {
				return err
			}
			if bytes.HasPrefix(data, []byte("!<arch>\n")) {
				t.Errorf("cache-only loading compiled an archive: %s", path)
			}
		}
		return nil
	}); err != nil {
		t.Fatal(err)
	}
	result = inspect(true)
	if !result.Complete {
		t.Fatal("actual imported type failed to resolve", result.Diagnostics)
	}
	if len(result.Declarations) != 1 || result.Declarations[0].Name != "New" {
		t.Fatal("provider reference unresolved", result.Declarations)
	}
	if result = inspect(false); !result.Complete {
		t.Fatal("cached export data not reused", result.Diagnostics)
	}
}

func TestCapturedTagsPlatformGenericsAndGeneratedSource(t *testing.T) {
	report, root := fixture(t)
	report.Metadata.BuildFlags = []string{"-tags=chosen"}
	report.Metadata.GOOS = "linux"
	sourceFile(t, root, "dep/dep.go", `//go:build chosen && linux

// Code generated by test; DO NOT EDIT.
package dep
type Box[T any] struct { Value T }
func New[T any](value T) Box[T] { return Box[T]{Value:value} }
func (box Box[T]) Get() T { return box.Value }
type Embed struct { N int }
type With struct { Embed }
type Protocol interface { Call() }
`)
	sourceFile(t, root, "dep/ignored.go", "//go:build !chosen\n\npackage dep\nvar _ = UndefinedSymbol\n")
	sourceFile(t, root, "dep/ignored_windows.go", "package dep\nvar _ = UndefinedSymbol\n")
	sourceFile(t, root, "consumer/consumer.go", `package consumer
import "example.org/repo/dep"
var Value = dep.New(7).Value
var Other = dep.New(8).Get()
var Embedded = dep.With{}.Embed
func UseProtocol(value dep.Protocol) { value.Call() }
`)
	data, err := Read(saveFixture(t, report, false))
	if err != nil {
		t.Fatal(err)
	}
	result, err := InspectRelationship(context.Background(), data, depName, "consumer", root, 10, TypeOptions{})
	if err != nil || !result.Complete {
		t.Fatal(result, err)
	}
	found := make(map[string]bool)
	for _, use := range result.Declarations {
		found[use.Name] = true
	}
	if !found["Box.Value"] || !found["Box.Get"] || !found["New"] || !found["With.Embed"] || !found["Protocol.Call"] || len(result.GeneratedFiles) != 1 {
		t.Fatal("generic bindings or source selection incorrect", found, result.GeneratedFiles)
	}
}
